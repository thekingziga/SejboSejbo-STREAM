function getLang(req) {
  const q = req.query?.lang;
  if (q === "sl" || q === "en") return q;
  const cookieHeader = String(req.headers?.cookie || "");
  if (cookieHeader.includes("sejbolive_lang=sl")) return "sl";
  if (cookieHeader.includes("sejbolive_lang=en")) return "en";
  return "en";
}

function getCopy(req) {
  return i18n[getLang(req)] || i18n.en;
}

function withLang(req, urlPath) {
  const lang = getLang(req);
  if (lang === "en") return urlPath;
  const sep = urlPath.includes("?") ? "&" : "?";
  return `${urlPath}${sep}lang=${lang}`;
}

module.exports = { i18n, getLang, getCopy, withLang };
